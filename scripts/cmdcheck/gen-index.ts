/**
 * Turns the output of scripts/cmdcheck/index-man.sh into src/cmdcheck_index.inc:
 * the options and subcommands each program's manual page cites, carried in the
 * binary for machines without manual pages.
 *   bun scripts/cmdcheck/gen-index.ts index.tsv "Ubuntu 24.04" > src/cmdcheck_index.inc
 */
import { readFileSync } from "node:fs";

/* C99 only promises 4095 characters per string literal (and -Wpedantic -Werror holds us to it). */
const CHUNK = 3800;
const WORD = /^[A-Za-z0-9][A-Za-z0-9-]*$/;

interface Entry {
  readonly program: string;
  readonly options: readonly string[];
  readonly subs: readonly string[];
}

function words(field: string, valid: (w: string) => boolean): string[] {
  return [...new Set(field.split(/\s+/).filter((w) => w !== "" && valid(w)))].sort();
}

/* The programs whose subcommands are checked: the SUBCOMMANDS list in src/cmdcheck_sh.c, the one source. */
function subcommandPrograms(): Set<string> {
  const c = readFileSync(new URL("../../src/cmdcheck_sh.c", import.meta.url), "utf8");
  const list = /SUBCOMMANDS\[\] = \{([^}]*)\}/.exec(c);
  if (!list) throw new Error("SUBCOMMANDS not found in src/cmdcheck_sh.c");
  return new Set([...list[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]));
}

function parse(tsv: string): Entry[] {
  const withSubs = subcommandPrograms();
  const entries: Entry[] = [];
  for (const line of tsv.replace(/\r/g, "").split("\n")) {
    if (line.trim() === "") continue;
    const [program, options = "", subs = ""] = line.split("\t");
    if (!/^[A-Za-z0-9_][A-Za-z0-9_.+-]*$/.test(program)) throw new Error(`bad program name: ${program}`);
    entries.push({
      program,
      options: words(options, (w) => /^--?[A-Za-z0-9][A-Za-z0-9-]*$/.test(w)),
      subs: withSubs.has(program) ? words(subs, (w) => WORD.test(w)) : [],
    });
  }
  return entries.sort((a, b) => a.program.localeCompare(b.program));
}

/* " a b c " pieces of at most CHUNK characters, so a lookup for " b " works in each. */
function chunks(list: readonly string[]): string[] {
  const out: string[] = [];
  let cur = " ";
  for (const w of list) {
    if (cur.length + w.length + 1 > CHUNK) {
      out.push(cur);
      cur = " ";
    }
    cur += `${w} `;
  }
  out.push(cur);
  return out;
}

function main(): void {
  const [file, source] = process.argv.slice(2);
  if (!file || !source) throw new Error("usage: gen-index.ts index.tsv \"Ubuntu 24.04\"");
  if (!/^[A-Za-z0-9 .()-]+$/.test(source)) throw new Error(`bad source name: ${source}`);
  const entries = parse(readFileSync(file, "utf8"));
  const rows: string[] = [];
  for (const e of entries) {
    const opts = chunks(e.options), subs = chunks(e.subs);
    for (let i = 0; i < Math.max(opts.length, subs.length); ++i)
      rows.push(`    {"${e.program}", "${opts[i] ?? " "}", "${subs[i] ?? " "}"},`);
  }
  const out = [
    "/* Generated by scripts/cmdcheck/gen-index.ts from scripts/cmdcheck/index-man.sh: the options and",
    ` * subcommands the manual pages cite (${source}), ${entries.length} programs. Names only, no text. */`,
    `#define CMDCHECK_INDEX_SOURCE "${source}"`,
    "static const IndexEntry INDEX[] = {",
    ...rows,
    "};",
    "",
  ];
  process.stdout.write(out.join("\n"));
}

main();
