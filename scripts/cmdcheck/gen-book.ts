/**
 * The command book for the runtime, from the one source (scripts/cmdcheck/livro.json and livro.ts):
 *   bun scripts/cmdcheck/gen-book.ts inc > src/book_data.inc        what src/book.c searches
 *   bun scripts/cmdcheck/gen-book.ts golden > tests/goldens/livro-busca.tsv
 * The .inc carries the stopwords, the constants, every stem with its weight (computed here, so C and
 * TypeScript add the very same doubles) and each task's phrases as stem numbers. The golden is what
 * livro.ts finds for every question of the eval sets and every phrase of the book, under both shells:
 * tests/test_book.c holds the C search to it, and tests/livro.test.ts keeps both files current.
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";

import { BONUS_FRASE, buscar, carregar, MAX_TAREFAS, MIN_PONTOS, SEGUNDA, type Shell, STOP } from "./livro";

const ROOT = join(import.meta.dir, "..", "..");
const SETS = ["tests/evals/livro/perguntas.json", "tests/evals/livro-2/perguntas.json",
  "tests/evals/docs-no-prompt/perguntas.json"];
const SHELLS: readonly Shell[] = ["powershell", "posix"];
const CHUNK = 3800; /* C99 only promises 4095 characters per string literal */

/* A C string literal: printable ASCII as is, the rest as octal escapes (UTF-8 bytes included). */
function cString(s: string): string {
  let out = "";
  for (const b of new TextEncoder().encode(s)) {
    const c = String.fromCharCode(b);
    out += b >= 0x20 && b < 0x7f && c !== '"' && c !== "\\" && c !== "?" ? c : `\\${b.toString(8).padStart(3, "0")}`;
  }
  return `"${out}"`;
}

function chunks(s: string): string {
  const parts: string[] = [];
  for (let i = 0; i < s.length; i += CHUNK) parts.push(cString(s.slice(i, i + CHUNK)));
  return parts.length ? parts.join("\n    ") : '""';
}

export function incText(): string {
  const livro = carregar();
  const stems = [...livro.peso.keys()].sort();
  const index = new Map(stems.map((w, i) => [w, i]));
  const out: string[] = [
    "/* Generated by scripts/cmdcheck/gen-book.ts from scripts/cmdcheck/livro.json and livro.ts: do not edit. */",
    "",
    `#define BOOK_MIN_POINTS ${MIN_PONTOS}`,
    `#define BOOK_SECOND ${SEGUNDA}`,
    `#define BOOK_PHRASE_BONUS ${BONUS_FRASE}`,
    `#define BOOK_TASKS_MAX ${MAX_TAREFAS}`,
    `#define BOOK_STEM_COUNT ${stems.length}`,
    `#define BOOK_TASK_COUNT ${livro.tarefas.length}`,
    "",
    "/* Words dropped before stemming, sorted (strcmp). */",
    `static const char *const BOOK_STOP[] = {\n    ${[...STOP].sort().map(cString).join(", ")}};`,
    "",
    "/* Every stem of the book's phrases, sorted (strcmp), and its weight: log(1 + tasks / tasks with it). */",
    `static const char *const BOOK_STEMS[BOOK_STEM_COUNT] = {\n    ${stems.map(cString).join(", ")}};`,
    `static const double BOOK_WEIGHT[BOOK_STEM_COUNT] = {\n    ${stems.map((w) => String(livro.peso.get(w)!)).join(", ")}};`,
    "",
    "/* Each task's phrases: stem numbers in the phrase's order, each once; -1 ends a phrase, -2 the task. */",
  ];
  livro.tarefas.forEach((t, i) => {
    const nums = livro.frases.get(t.id)!.flatMap((f) => [...f.map((w) => index.get(w)!), -1]);
    out.push(`static const short BOOK_PHRASES_${i}[] = {${[...nums, -2].join(", ")}};`);
  });
  out.push("", "static const BookTask BOOK_TASKS[BOOK_TASK_COUNT] = {");
  livro.tarefas.forEach((t, i) => {
    out.push(`    {${cString(t.id)}, BOOK_PHRASES_${i},\n     ${chunks(t.powershell.join("\n"))},\n     ` +
      `${chunks(t.posix.join("\n"))}},`);
  });
  out.push("};", "");
  return out.join("\n");
}

interface Pergunta { readonly pergunta: string }

/* Lines of "shell<TAB>question<TAB>task,task": every question once per shell, in a fixed order. */
export function goldenText(): string {
  const livro = carregar();
  const questions = new Set<string>();
  for (const set of SETS) {
    const p = (JSON.parse(readFileSync(join(ROOT, set), "utf8")) as { perguntas: Pergunta[] }).perguntas;
    for (const q of p) questions.add(q.pergunta);
  }
  for (const t of livro.tarefas) for (const f of t.frases) questions.add(f);
  const lines = ["# Generated by scripts/cmdcheck/gen-book.ts golden: what scripts/cmdcheck/livro.ts finds."];
  for (const q of questions) {
    if (/[\t\n\r]/.test(q)) throw new Error(`question with a tab or newline: ${q}`);
    for (const s of SHELLS) lines.push(`${s}\t${q}\t${buscar(livro, q, s).map((a) => a.tarefa.id).join(",")}`);
  }
  return `${lines.join("\n")}\n`;
}

if (import.meta.main) {
  const what = process.argv[2];
  if (what === "inc") process.stdout.write(incText());
  else if (what === "golden") process.stdout.write(goldenText());
  else throw new Error("uso: bun scripts/cmdcheck/gen-book.ts inc|golden");
}
